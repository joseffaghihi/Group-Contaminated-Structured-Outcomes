#!/usr/bin/env python3
"""Build TeX macros for the explicitly post-outcome robustness extensions."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def _renew(name: str, value: str) -> str:
    return rf"\renewcommand{{\{name}}}{{{value}}}"


def _verify_recorded_hash(audit: dict, path: Path) -> None:
    record = audit.get("outputs", {}).get(path.name)
    if not isinstance(record, dict) or "sha256" not in record:
        raise RuntimeError(f"Extension audit has no hash for {path.name}.")
    observed = _sha256(path)
    if observed != str(record["sha256"]):
        raise RuntimeError(
            f"Extension output hash mismatch for {path.name}: "
            f"expected {record['sha256']}, observed {observed}."
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--sensitivity",
        type=Path,
        default=ROOT / "results/extensions/rosenbaum_sensitivity.csv",
    )
    parser.add_argument(
        "--sensitivity-summary",
        type=Path,
        default=ROOT / "results/extensions/rosenbaum_summary.json",
    )
    parser.add_argument(
        "--persistence-summary",
        type=Path,
        default=ROOT / "results/extensions/persistence_summary.json",
    )
    parser.add_argument(
        "--audit",
        type=Path,
        default=ROOT / "results/extensions/expert_review_extension_audit.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "paper/extension_results.tex",
    )
    args = parser.parse_args()

    audit = json.loads(args.audit.read_text())
    if audit.get("analysis_status") != "post_outcome_exploratory_extension":
        raise RuntimeError("The extension audit lost its post-outcome designation.")
    for path in (
        args.sensitivity,
        args.sensitivity_summary,
        args.persistence_summary,
    ):
        _verify_recorded_hash(audit, path)

    sensitivity = pd.read_csv(args.sensitivity)
    sensitivity_summary = json.loads(args.sensitivity_summary.read_text())
    persistence_summary = json.loads(args.persistence_summary.read_text())
    for payload in (sensitivity_summary, persistence_summary):
        if payload.get("analysis_status") != "post_outcome_exploratory_extension":
            raise RuntimeError("An extension result lost its post-outcome designation.")

    rows = []
    for row in sensitivity.itertuples(index=False):
        rows.append(
            f"{float(row.gamma):.2f} & {float(row.upper_probability):.6f} \\\\"
        )
    critical = sensitivity_summary["critical_gamma"]
    if not bool(critical.get("crossed", False)):
        raise RuntimeError("The requested 0.05 sensitivity crossing was not found.")

    lines = [
        "% Generated by scripts/build_extension_results_tex.py; do not hand edit.",
        r"\extensionsavailabletrue",
        _renew("RxSensitivityRows", "\n".join(rows)),
        _renew("RxSensitivityCritical", f"{float(critical['critical_gamma']):.6f}"),
        _renew(
            "RxSensitivityCriticalP",
            f"{float(critical['upper_p_at_critical_gamma']):.6f}",
        ),
        _renew(
            "RxExtensionExactP",
            f"{float(sensitivity_summary['exact_randomization_p_value']):.7f}",
        ),
        _renew("RxPersistenceSites", str(int(persistence_summary["sites"]))),
        _renew(
            "RxPersistenceInvariantChecks",
            str(int(persistence_summary["exact_persistence_invariance_checks_passed"])),
        ),
        _renew(
            "RxPersistenceStabilityChecks",
            str(int(persistence_summary["stability_checks_passed"])),
        ),
        _renew(
            "RxPersistenceKernelChecks",
            str(int(persistence_summary["kernel_link_checks_passed"])),
        ),
        _renew(
            "RxPersistenceMaxExactBottleneck",
            f"{float(persistence_summary['maximum_exact_action_bottleneck']):.6f}",
        ),
        _renew(
            "RxPersistenceMaxPerturbedBottleneck",
            f"{float(persistence_summary['maximum_perturbation_bottleneck']):.6f}",
        ),
        _renew(
            "RxPersistenceMaxSupNorm",
            f"{float(persistence_summary['maximum_realized_sup_norm']):.6f}",
        ),
        _renew(
            "RxExtensionAuditHash",
            _sha256(args.audit),
        ),
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_suffix(args.output.suffix + ".tmp")
    temporary.write_text("\n".join(lines) + "\n")
    temporary.replace(args.output)
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

